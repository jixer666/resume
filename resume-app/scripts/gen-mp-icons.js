#!/usr/bin/env node
/**
 * 生成 src/components/mp-icons.ts
 *
 * 事实源：resume-design 的 iconfont SVG sprite（`public/static/iconfont/iconfont.js`）
 * 生成物：src/components/mp-icons.ts —— 只保留项目实际引用到的图标
 *
 * 背景：resume-design 用 `<svg><use xlink:href="#icon-x"/></svg>` 渲染图标，
 *      小程序不支持内联 `<svg>`，故把 symbol 抽成「viewBox + path 片段」，
 *      运行时由 `MpIcon.vue` 拼成 data-URI 背景图（UnoCSS preset-icons 在小程序端同款做法）。
 *
 * 用法：
 *   node ./scripts/gen-mp-icons.js                 # 用默认 sprite 路径
 *   node ./scripts/gen-mp-icons.js <sprite.js>     # 指定 sprite
 *   MP_ICON_SPRITE=<sprite.js> node ./scripts/gen-mp-icons.js
 */
import fs from 'node:fs'
import path from 'node:path'
import process from 'node:process'

const ROOT = process.cwd()
const DEFAULT_SPRITE = path.resolve(
  ROOT,
  '../../../vue/resume-project/resume-design/public/static/iconfont/iconfont.js',
)
const SPRITE_PATH = path.resolve(
  process.argv[2] || process.env.MP_ICON_SPRITE || DEFAULT_SPRITE,
)
const OUT_FILE = path.resolve(ROOT, 'src/components/mp-icons.ts')
const SCAN_DIRS = ['src/material', 'src/schema']

/** 递归收集目录下所有指定后缀的文件 */
function walk(dir, exts, acc = []) {
  if (!fs.existsSync(dir))
    return acc
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name)
    if (entry.isDirectory())
      walk(full, exts, acc)
    else if (exts.includes(path.extname(entry.name)))
      acc.push(full)
  }
  return acc
}

/** 扫描源码里实际引用到的 icon-xxx 名称 */
function collectUsedIcons() {
  const names = new Set()
  const files = SCAN_DIRS.flatMap(dir => walk(path.resolve(ROOT, dir), ['.vue', '.ts']))
  for (const file of files) {
    const source = fs.readFileSync(file, 'utf8')
    // 静态写法：<svg-icon icon-name="icon-xxx" />
    for (const match of source.matchAll(/icon-name="(icon-[\w-]+)"/gi))
      names.add(match[1].toLowerCase())
    // 默认数据：MODEL_DATA_JSON 里的 iconfont 字段（动态 :icon-name 的取值来源）
    for (const match of source.matchAll(/iconfont:\s*['"]([^'"]+)['"]/gi))
      names.add(match[1].toLowerCase())
  }
  return [...names].filter(name => name.startsWith('icon-')).sort()
}

/** 从 iconfont sprite 中抽取 symbol */
function readSymbols() {
  if (!fs.existsSync(SPRITE_PATH))
    throw new Error(`找不到 iconfont sprite：${SPRITE_PATH}\n可用 MP_ICON_SPRITE 环境变量指定路径`)
  const source = fs.readFileSync(SPRITE_PATH, 'utf8')
  const symbols = new Map()
  for (const match of source.matchAll(/<symbol\s+id="([^"]+)"\s+viewBox="([^"]*)"[^>]*>([\s\S]*?)<\/symbol>/g)) {
    symbols.set(match[1].toLowerCase(), { v: match[2], b: match[3].trim() })
  }
  return symbols
}

function main() {
  const used = collectUsedIcons()
  const symbols = readSymbols()

  const entries = []
  const missing = []
  for (const name of used) {
    const symbol = symbols.get(name)
    if (symbol)
      entries.push([name, symbol])
    else
      missing.push(name)
  }

  const lines = entries.map(
    ([name, { v, b }]) => `  ${JSON.stringify(name)}: { v: ${JSON.stringify(v)}, b: ${JSON.stringify(b)} },`,
  )

  const banner = [
    '/* eslint-disable */',
    '// AUTO-GENERATED by scripts/gen-mp-icons.js —— 请勿手改',
    '// 图标来源：resume-design/public/static/iconfont/iconfont.js',
    '// 重新生成：pnpm gen:icons',
    '',
  ].join('\n')

  const content = `${banner}
export interface IMpIconSymbol {
  /** <svg viewBox> */
  v: string
  /** <symbol> 内部片段（path 等） */
  b: string
}

/** 已抽取的图标表，key 为 iconfont 的 icon-xxx 名称 */
export const MP_ICONS: Record<string, IMpIconSymbol> = {
${lines.join('\n')}
}
`

  fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true })
  fs.writeFileSync(OUT_FILE, content, 'utf8')

  console.log(`[gen:icons] sprite   -> ${SPRITE_PATH}`)
  console.log(`[gen:icons] 扫描引用 -> ${used.length} 个`)
  console.log(`[gen:icons] 已抽取   -> ${entries.length} 个`)
  console.log(`[gen:icons] 输出     -> ${path.relative(ROOT, OUT_FILE)}`)
  if (missing.length)
    console.warn(`[gen:icons] 警告：sprite 中缺失 ${missing.length} 个图标 -> ${missing.join(', ')}`)
}

main()
